    private void btnVerInstruccionesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerInstruccionesActionPerformed
        
    //Nos permite obtiener la posición del ejercicio seleccionado
    int posicion = lstEjercicios.getSelectedIndex();

    //Nos permite verificar que se haya seleccionado un ejercicio
    if (posicion == -1) {
        JOptionPane.showMessageDialog(this,
                "Debe seleccionar un ejercicio de la lista.");
        return;
    }

    //Nos permite consultar el catálogo de ejercicios
    CatalogoEjercicios catalogo = new CatalogoEjercicios();

    //Nos permite obtiener el ejercicio seleccionado
    Ejercicio ejercicio =
            catalogo.consultarEjercicios().get(posicion);

    // Se muestran las instrucciones del ejercicio.
    JOptionPane.showMessageDialog(this,
            ejercicio.mostrarInformacion(),
            "Información del ejercicio",
            JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnVerInstruccionesActionPerformed

    private void btnCrearRutinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearRutinaActionPerformed
        
    //Lo utilizamos para verificar que el usuario haya iniciado sesión
    if (usuarioActual == null) {
        JOptionPane.showMessageDialog(this,
                "Debe iniciar sesión para crear una rutina.");
        return;
    }

    //Nos permite obtener las posiciones de todos los ejercicios seleccionados
    int[] posiciones = lstEjercicios.getSelectedIndices();

    //Se verifica que exista al menos un ejercicio seleccionado
    if (posiciones.length == 0) {
        JOptionPane.showMessageDialog(this,
                "Debe seleccionar al menos un ejercicio.");
        return;
    }

    //Se solicita el nombre de la rutina
    String nombre = JOptionPane.showInputDialog(this,
            "Ingrese el nombre de la rutina:");

    //Se comprueba que el nombre sea válido
    if (nombre == null || nombre.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Debe ingresar un nombre para la rutina.");
        return;
    }

    //Se obtiene el catálogo de ejercicios
    CatalogoEjercicios catalogo = new CatalogoEjercicios();

    //Se crea la rutina para el usuario
    Rutina rutina = servicioRutinas.crearRutina(
            usuarioActual, nombre);

    //Se prepara el texto para mostrar los ejercicios agregados
    String ejerciciosAgregados = "";

    //Se recorren todos los ejercicios seleccionados
    for (int posicion : posiciones) {

        Ejercicio ejercicio =
                catalogo.consultarEjercicios().get(posicion);

        //Se agrega cada ejercicio a la misma rutina
        rutina.agregarEjercicio(ejercicio);

        //Se agrega su nombre al mensaje de confirmación
        ejerciciosAgregados += "\n- " + ejercicio.getNombre();
    }

    //Se muestra la confirmación de la rutina creada
    JOptionPane.showMessageDialog(this,
            "Rutina creada correctamente."
            + "\nNombre: " + rutina.getNombre()
            + "\nEjercicios agregados:"
            + ejerciciosAgregados);
    }//GEN-LAST:event_btnCrearRutinaActionPerformed

