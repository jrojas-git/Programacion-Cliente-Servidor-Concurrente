    //Lo utilizamos para poder carga los ejercicios disponibles en la lista
    private void cargarEjercicios() {

        //Nos permite crear el catálogo de ejercicios
        CatalogoEjercicios catalogo = new CatalogoEjercicios();

        //Nos permite crear el modelo que utilizará la lista
        DefaultListModel<String> modelo = new DefaultListModel<>();

        //Nos permite recorrer los ejercicios del catálogo
        for (Ejercicio ejercicio : catalogo.consultarEjercicios()) {

            //Nos permite agregar el nombre de cada ejercicio
            modelo.addElement(ejercicio.getNombre());
        }

        //Lo utilizamos para mostrar los ejercicios en la lista
        lstEjercicios.setModel(modelo);
    }

