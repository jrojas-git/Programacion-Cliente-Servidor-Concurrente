    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed

    //Lo utilizamos para obtener el nombre de usuario ingresado
    String nombreUsuario = txtUsuario.getText();

    //Lo utilizamos para obtener la contraseña ingresada
    String contrasena = new String(txtContrasena.getPassword());

    //Nos permite crear el servicio para verificar los datos
    ServicioAutenticacion servicio = new ServicioAutenticacion();

    try {

        //Se comprueba si los datos son correctos
        Usuario usuario = servicio.autenticar(
                nombreUsuario, contrasena);

        //Se muestra un mensaje de bienvenida
        JOptionPane.showMessageDialog(this,
                "Bienvenido a Fidness, "
                + usuario.getNombreUsuario());

        //Se abre el catálogo con el usuario autenticado
        VentanaCatalogo catalogo = new VentanaCatalogo(usuario);
        catalogo.setLocationRelativeTo(null);
        catalogo.setVisible(true);

        //Se cierra la ventana de inicio de sesión
        this.dispose();

    } catch (ExcepcionUsuario ex) {

        //Se muestra el error si los datos son incorrectos
        JOptionPane.showMessageDialog(this,
                ex.getMessage(),
                "Error de inicio de sesión",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnIniciarSesionActionPerformed

